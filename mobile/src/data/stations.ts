function makeBays(
  prefix: string,
  powerKw: number,
  statuses: ChargingBay['status'][]
): ChargingBay[] {
  return statuses.map((status, idx) => ({
    id: `${prefix}-bay-${idx + 1}`,
    code: `${prefix}-0${idx + 1}`,
    connector: 'CCS2 DC',
    powerKw,
    status,
    occupiedSinceMin: status === 'occupied' ? 12 + idx * 6 : undefined,
    estimatedFreeInMin: status === 'occupied' ? 8 + idx * 5 : undefined,
  }));
}

